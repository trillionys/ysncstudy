def _norm(s):
    s = unicodedata.normalize("NFC", s or "").lower()
    return re.sub(r"[\s·ㆍ,()\[\]\-]", "", s)


def items_of(text):
    """공백 구분 목록을 항목으로 나눈다. COMPOUND 의 복합 항목은 하나로 유지한다."""
    out, rest = [], text
    for c in sorted(COMPOUND, key=len, reverse=True):
        if c in rest:
            out.append((rest.index(c), c))
            rest = rest.replace(c, " " * len(c), 1)
    out += [(m.start(), m.group()) for m in re.finditer(r"\S+", rest)]
    return [w for _, w in sorted(out)]


